"""Regenerate documentation/schema artifacts; --check detects declaration drift."""
import argparse
import json
from pathlib import Path
from schemaxis.schema import declarations, export_schema
from schemaxis.camera import CAMERA
from schemaxis.adaptors.registry import ADAPTORS, binding, routes
from schemaxis.functions import FUNCTIONS


def code(value):
    return '`' + json.dumps(value, ensure_ascii=False, separators=(',', ':')).replace('|', '&#124;') + '`'


def cell(text):
    return ' '.join(str(text).split()).replace('|', '&#124;')


def rows(specs, meanings=None):
    """Option table; ``meanings`` adds the conceptual guidance shown in Studio."""
    head = '| Option | Meaning | Type / constraints | Default |' if meanings is not None else '| Option | Type / constraints | Default |'
    lines = [head, '| --- | --- | --- | --- |' if meanings is not None else '| --- | --- | --- |']
    for key, spec in specs.items():
        constraint = {k: v for k, v in spec.items() if k not in ('default', 'required', 'title', 'summary')}
        default = '**required**' if spec.get('required') else code(spec['default']) if 'default' in spec else 'omitted'
        meaning = '' if meanings is None else ' ' + cell(meanings.get(key, {}).get('explanation', '')) + ' |'
        lines.append('| `' + key + '` |' + meaning + ' ' + code(constraint) + ' | ' + default + ' |')
    return lines


def operation_help(record):
    """Conceptual operation guidance as reference lines; pending records add nothing."""
    if not record or record.get('status') == 'pending' or not record.get('explanation'):
        return []
    lines = [record['explanation'], '']
    if record.get('pitfalls'):
        lines += ['Common mistakes and assumptions:', ''] + ['- ' + ' '.join(item.split()) for item in record['pitfalls']] + ['']
    return lines


def module_index():
    import ast
    root=Path(__file__).resolve().parent
    modules=[]
    for path in sorted(root.rglob('*.py')):
        tree=ast.parse(path.read_text())
        dependencies=sorted({'.'*n.level+(n.module or '') for n in ast.walk(tree) if isinstance(n,ast.ImportFrom)} |
                            {a.name for n in ast.walk(tree) if isinstance(n,ast.Import) for a in n.names})
        relative=path.relative_to(root)
        modules.append({'module':'schemaxis.'+'.'.join(relative.with_suffix('').parts),
            'file':'src/schemaxis/'+relative.as_posix(),'imports':dependencies})
    lines=['# Module index','','Generated statically; importing native applications is unnecessary.','',
           '| Module | Source |','| --- | --- |']
    lines += ['| `'+m['module']+'` | ['+m['file']+'](../../'+m['file']+') |' for m in modules]
    return {'modules.json':json.dumps(modules,indent=2)+'\n','modules.md':'\n'.join(lines)+'\n'}


def artifacts():
    result = {}
    from schemaxis.adaptors.registry import ADAPTORS
    from .studio_guidance import load, option_guidance
    for provider in ADAPTORS:
        catalogue = declarations(provider)
        guidance = load(provider)
        meanings = option_guidance(provider)
        root = {}
        for version in ADAPTORS[provider]['routes']:
            for address, record in guidance['routes'].get(version, {}).get('fields', {}).items():
                if address.count('/') == 2 and address.startswith('/properties/') and record.get('explanation'):
                    root.setdefault(address.split('/')[2], record)
        lines = ['# ' + provider.title() + ' operation reference', '',
                 'Generated from the current declarations. Do not edit this file by hand.', '',
                 'Types, limits and defaults below describe **resolved values**. Runtime expressions',
                 'must produce these types. Unknown options are rejected; defaults apply only when omitted.',
                 'Constructor options must be constant after document composition.', '',
                 '## Index', '', ', '.join('[' + n + '](#' + n.lower() + ')' for n in sorted(catalogue)), '']
        if ADAPTORS[provider].get('referenceIntro'):
            lines[4:7] = ADAPTORS[provider]['referenceIntro']
        for name, d in sorted(catalogue.items()):
            lines += ['## ' + name, '', *operation_help(guidance['operations'].get(name)),
                      'Native binding: `' + d['native'] + '`. Output kind: ' + code(d.get('kinds', ['data'])) + '.', '']
            if d.get('coverage'):
                lines += ['Coverage: ' + code(d['coverage']) + '.', '']
            if d.get('role') == 'writer':
                lines += ['Role: scene export writer (not a pipeline node).', '',
                          'Publication contract: ' + code(d['publication']) + '.', '']
            if d['inputs']:
                lines += ['| Input port | Multiplicity | Required | Kind |', '| --- | --- | --- | --- |']
                for p, spec in d['inputs'].items():
                    lines.append('| `' + p + '` | ' + ('nonempty list' if spec.get('multiple') else 'one node') +
                                 ' | ' + ('yes' if spec.get('required') else 'no') + ' | `' + spec.get('kind', 'data') + '` |')
                lines += ['']
                for p, spec in d['inputs'].items():
                    if spec.get('contract'):
                        lines += ['Input `' + p + '` contract: ' + code(spec['contract']) + '.', '']
            else:
                lines += ['Inputs: none.', '']
            explained = {**{k: root[k] for k in d['options'] if k in root}, **meanings.get(name, {})}
            lines += rows({k: v['value'] for k, v in d['options'].items()}, explained) if d['options'] else ['Options: none.']
            if d.get('commands'):
                lines += ['', '`onVisit` commands: ' + code(d['commands']) +
                          '. Invoked in authored order on every selected visit, before updating this node; downstream results are invalidated.']
            lines += ['']
            for k, v in d['options'].items():
                if v.get('constructor'):
                    lines += ['- `' + k + '` is a constructor option.']
                if v.get('convert'):
                    lines += ['- `' + k + '` uses the `' + v['convert'] + '` conversion described in the input guide.']
                if v.get('compiler'):
                    lines += ['- `' + k + '` is a closed structured value; Schemaxis compiles it with `' + v['compiler'] +
                              '` and checks the result again before native assignment. Native text is never accepted.']
                if v.get('tupleSize'):
                    lines += ['- `' + k + '` requires complete groups of ' + str(v['tupleSize']) + ' values.']
                if v.get('tupleElementTypes'):
                    lines += ['- `' + k + '` tuple positions are ' + ', '.join(v['tupleElementTypes']) +
                              '; an `index` position is a non-negative integer written as digits.']
            for key in ('requires', 'checks'):
                if d.get(key):
                    lines += ['', 'Cross-option ' + key + ': ' + code(d[key]) + '.']
            lines += ['']
        result[provider + '-operations.md'] = '\n'.join(lines).rstrip() + '\n'
        result[provider + '.schema.json'] = json.dumps(export_schema(provider), indent=2, ensure_ascii=False) + '\n'
    lines = ['# Shared settings and runtime functions', '', 'Generated from current code declarations. Do not edit by hand.', '']
    settings = [('Camera', CAMERA)] + [(name, binding(path)) for item in ADAPTORS.values() for name, path in item.get('referenceSettings', {}).items()]
    for name, spec in settings:
        lines += ['## ' + name, '', *rows(spec), '']
    for name, spec in FUNCTIONS.describe().items():
        lines += ['## ' + name, '', *rows(spec['arguments']), '', 'Result: ' + code(spec['result']) + '.', '']
    for _, route in routes().values():
        if route.get('referenceName'):
            result[route['referenceName'] + '.schema.json'] = json.dumps(export_schema(section=route['schemaName']), indent=2) + '\n'
    # Standalone authored/umbrella files contain the full catalogue recursively.
    # Compact JSON avoids multiplying their footprint with indentation alone.
    from schemaxis.schema_authoring import VERSIONS, version_schema, umbrella_schema
    names = {r['schemaName']: r['referenceName'] for _, r in routes().values() if r.get('referenceName')}
    for version, kind in VERSIONS.items():
        name = names.get(kind, kind)
        result[name + '.authored.schema.json'] = json.dumps(
            version_schema(version, authored=True), ensure_ascii=False, separators=(',', ':')) + '\n'
        if kind == 'workflow':
            result[name + '.schema.json'] = json.dumps(
                version_schema(version), ensure_ascii=False, separators=(',', ':')) + '\n'
    for authored in (True, False):
        name = 'schemaxis-' + ('authored' if authored else 'expanded') + '.schema.json'
        result[name] = json.dumps(umbrella_schema(authored=authored), ensure_ascii=False, separators=(',', ':')) + '\n'
    for section in ('execution', 'operation-execution', 'composition', 'analytic'):
        result[section + '.schema.json'] = json.dumps(export_schema(section=section), indent=2) + '\n'
    result['analytic.authored.schema.json'] = json.dumps(
        export_schema(section='analytic', authored=True), indent=2) + '\n'
    result['settings.md'] = '\n'.join(lines).rstrip() + '\n'
    from .adaptor_delivery import reference_page
    result['adaptor-delivery.md'] = reference_page()
    result.update(module_index())
    return result


def generate(directory=None, *, check=False):
    from .errors import fail
    plugins = sorted(name for name, item in ADAPTORS.items() if item.get('source', 'builtin') != 'builtin')
    if directory is None and plugins:
        fail('PLUGIN_ADAPTORS_LOADED', 'the core reference covers built-in adaptors only; set '
             'SCHEMAXIS_ADAPTOR_PLUGINS=off, or pass --output-directory for a reference including plugins',
             'reference', plugins=plugins)
    directory = Path(directory) if directory is not None else Path(__file__).resolve().parents[2]/'docs/generated'
    expected = artifacts()
    if check:
        stale = [name for name, content in expected.items() if not (directory/name).exists() or (directory/name).read_text() != content]
        if stale: fail('STALE_REFERENCE', 'regenerate schemas and documentation', files=stale)
        return {'verified':True,'files':len(expected),'directory':str(directory)}
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in expected.items(): (directory/name).write_text(content)
    return {'generated':len(expected),'directory':str(directory)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output-directory',type=Path)
    args=parser.parse_args()
    print(json.dumps(generate(args.output_directory,check=args.check),indent=2))


if __name__ == '__main__': main()
