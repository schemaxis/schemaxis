"""Bind every payload member of a saved sourced assembly to independent evidence (host only).

Evidence for each rule (FreeCAD 1.1.4, Document.copyObject into one assembly):
- Source BREP payloads stay byte-identical except that a producer token `-0.000…` may be
  written as `0.000…` at the same position. No other lexical or numeric change is accepted.
- Source element maps are re-serialised against the assembly's merged string hasher.
  Their structure is bound: the section skeleton, child lines and postfix tables (with
  object tags remapped and hasher IDs masked), which postfix table each map uses, tags that
  name only the same source's objects, and hasher references inside the merged table.
  The encoded name entries of later-copied sources are counted, not decoded: decoding
  them would need FreeCAD's element-map and string-hasher encoding, so they are a stated
  limit. Element maps are regenerated by FreeCAD on recompute and carry no references
  used by the qualified source route.
- Generated helpers: link PlacementList/ScaleList members are the empty list (four zero
  bytes); a mount's datum shape is a fixed planar-face BREP whose location rows equal
  the saved mount placement.
"""
import re

from .source_envelope import element_map, read_members, string_table

ZERO = re.compile(rb'0\.0+')
TAG = re.compile(r';:H(-?)([0-9a-f]+)')
HASH_ID = re.compile(r'#[0-9a-f]+')
EMPTY_LIST = b'\x00\x00\x00\x00'
DATUM_TEMPLATE = (
    '\nCASCADE Topology V1, (c) Matra-Datavision\nLocations 1\n1\nCurve2ds 0\nCurves 0\nPolygon3D 0\n'
    'PolygonOnTriangulations 0\nSurfaces 1\n1 0.00000000000000000 0.00000000000000000 0.00000000000000000 '
    '0.00000000000000000 0.00000000000000000 1.00000000000000000 1.00000000000000000 0.00000000000000000 '
    '-0.00000000000000000 -0.00000000000000000 1.00000000000000000 0.00000000000000000 \nTriangulations 0\n\n'
    'TShapes 1\nFa\n1  0.000000100000000 1 0\n\n1101000\n*\n\n+1 1 ').split('\n')


def same_brep(producer, embedded):
    """Byte equality, except producer `-0.0…` written as embedded `0.0…` at the same token."""
    if producer == embedded:
        return True
    old, new = producer.split(b'\n'), embedded.split(b'\n')
    if len(old) != len(new):
        return False
    for a, b in zip(old, new):
        if a == b:
            continue
        ta, tb = a.split(b' '), b.split(b' ')
        if len(ta) != len(tb):
            return False
        for u, v in zip(ta, tb):
            if u != v and not (u == b'-'+v and ZERO.fullmatch(v)):
                return False
    return True


def _zero(token):
    return re.fullmatch(r'-?0\.0+', token) is not None


def datum_brep(data, matrix):
    """The fixed datum template, with location rows equal to the mount placement (15 decimals)."""
    try:
        lines = data.decode('ascii').split('\n')
    except UnicodeDecodeError:
        return False
    if len(lines) != len(DATUM_TEMPLATE) + 3 or [l for i, l in enumerate(lines) if i not in (4, 5, 6)] != DATUM_TEMPLATE:
        return False
    for row in range(3):
        tokens = lines[4+row].split(' ')
        if len(tokens) != 5 or tokens[4] != '':
            return False
        for column, token in enumerate(tokens[:4]):
            wanted = format(matrix[row*4+column], '.15f')
            if token != wanted and not (_zero(token) and _zero(wanted)):
                return False
    return True


def _remap(text, ids):
    return TAG.sub(lambda m: ';:H'+m.group(1)+format(ids[int(m.group(2), 16)], 'x'), text)


def _child(line, ids):
    tokens = _remap(line, ids).split(' ')
    if len(tokens) > 3 and tokens[3].isdigit() and int(tokens[3]) in ids:
        tokens[3] = str(ids[int(tokens[3])])
    return ' '.join(tokens)


def file_map(root):
    """(object, property, element tag) -> member name, for every file-bearing element."""
    result = {}
    for obj in root.find('ObjectData').findall('Object'):
        for prop in obj.find('Properties').findall('Property'):
            for element in prop.iter():
                if element.get('file'):
                    key = (obj.get('name'), prop.get('name'), element.tag)
                    if key in result:
                        raise ValueError('duplicate payload reference '+str(key))
                    result[key] = element.get('file')
    return result


def object_ids(root):
    return {o.get('name'): int(o.get('id')) for o in root.find('Objects').findall('Object')}


def bind(prepared, path, root, renames, retained, placement):
    """Raise ValueError unless every assembly payload is bound; `placement(name)` reads saved placements."""
    code = 'VERIFICATION_FAILED'
    members = read_members(path, 'model.FCStd', code)
    files = file_map(root)
    table_member = root.find('StringHasher2').get('file')
    named = list(files.values()) + [table_member]
    if len(set(named)) != len(named):
        raise ValueError('a payload member is referenced twice')
    if set(members) != {'Document.xml', 'GuiDocument.xml', *named}:
        raise ValueError('assembly archive members differ from the payloads its document names: extra '
                         + str(sorted(set(members) - {'Document.xml', 'GuiDocument.xml', *named}))
                         + ' missing ' + str(sorted({*named} - set(members))))
    table = string_table(members[table_member], 'model.FCStd', code, table_member)
    assembly_ids = object_ids(root)
    owned = set()
    for part in prepared['parts']:
        mapping = renames[part['id']]
        producer_members = read_members(retained[part['id']], part['id'], code)
        from xml.etree import ElementTree as ET
        producer_root = ET.fromstring(producer_members['Document.xml'])
        producer_files = file_map(producer_root)
        producer_ids = object_ids(producer_root)
        ids = {producer_ids[name]: assembly_ids[mapping[name]] for name in producer_ids}
        own_ids = {assembly_ids[name] for name in mapping.values()}
        produced_tables, embedded_tables, pairs = {}, {}, []
        for (obj, prop, tag), producer_file in producer_files.items():
            key = (mapping[obj], prop, tag)
            embedded_file = files.get(key)
            if embedded_file is None:
                raise ValueError('embedded payload reference is missing for '+str(key))
            owned.add(key)
            old, new = producer_members[producer_file], members[embedded_file]
            if tag == 'Part':
                if not same_brep(old, new):
                    raise ValueError('embedded shape payload differs from its producer: '+embedded_file)
            elif tag == 'ElementMap2':
                p = element_map(old, part['id'], code, producer_file)
                e = element_map(new, 'model.FCStd', code, embedded_file)
                produced_tables[p['postfixId']] = (obj, prop, tag)
                if e['postfixId'] in embedded_tables:
                    raise ValueError('postfix table defined twice in one source: '+embedded_file)
                embedded_tables[e['postfixId']] = key
                pairs.append((p, e, embedded_file))
            else:
                raise ValueError('unqualified source payload kind: '+embedded_file)
        for p, e, member in pairs:
            if not e['tags'] <= own_ids or any(h > table for h in e['hashes']):
                raise ValueError('element map refers outside its source or the string table: '+member)
            masked = sorted(HASH_ID.sub('#', _remap(x, ids)) for x in p['postfixes'])
            if masked != sorted(HASH_ID.sub('#', x) for x in e['postfixes']):
                raise ValueError('element map postfix table differs from its producer: '+member)
            if len(p['maps']) != len(e['maps']):
                raise ValueError('element map count differs from its producer: '+member)
            for (pt, ps), (et, es) in zip(p['maps'], e['maps']):
                origin = produced_tables.get(pt)
                if origin is None or embedded_tables.get(et) != (mapping[origin[0]], origin[1], origin[2]):
                    raise ValueError('element map uses another postfix table than its producer: '+member)
                if [(k, c, n) for k, c, n, _, _ in ps] != [(k, c, n) for k, c, n, _, _ in es]:
                    raise ValueError('element map skeleton differs from its producer: '+member)
                if [_child(l, ids) for *_, ch, _ in ps for l in ch] != [l for *_, ch, _ in es for l in ch]:
                    raise ValueError('element map child records differ from their producer: '+member)
    native = prepared['native']
    for key, mount in native['mounts'].items():
        member = files.get((mount, 'Shape', 'Part'))
        if member is None or not datum_brep(members[member], placement(mount)):
            raise ValueError('mount datum shape differs from its saved placement: '+key)
        owned.add((mount, 'Shape', 'Part'))
    for name in native['components'].values():
        for prop, tag in (('PlacementList', 'PlacementList'), ('ScaleList', 'VectorList')):
            member = files.get((name, prop, tag))
            if member is None or members[member] != EMPTY_LIST:
                raise ValueError('component link list is not the empty list: '+name+'.'+prop)
            owned.add((name, prop, tag))
    if set(files) != owned:
        raise ValueError('assembly carries payloads with no qualified owner: '+str(sorted(set(files) - owned)))
    return {'members': len(members), 'boundPayloads': len(owned), 'stringTable': table}
