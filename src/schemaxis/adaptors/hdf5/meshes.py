"""writeMeshFields: unstructured mesh, per-step point/cell fields and an XDMF 3 temporal description.

The mesh intent is translated into ordinary planned HDF5 objects (/mesh/points, /mesh/<block>/connectivity,
/fields/<name>/<step>, /time), so the same host expectations and both independent consumers apply. The
XDMF text is generated by the host from the plan and checked again by parsing it with the standard library:
every DataItem must name an existing dataset of matching dimensions and precision.
"""
import math
import xml.etree.ElementTree as ElementTree

from schemaxis.errors import fail
from . import model, operations

NODES = {'vertex': 1, 'line': 2, 'triangle': 3, 'quadrilateral': 4, 'tetrahedron': 4, 'pyramid': 5, 'wedge': 6, 'hexahedron': 8}
TOPOLOGY = {'vertex': 'Polyvertex', 'line': 'Polyline', 'triangle': 'Triangle', 'quadrilateral': 'Quadrilateral',
            'tetrahedron': 'Tetrahedron', 'pyramid': 'Pyramid', 'wedge': 'Wedge', 'hexahedron': 'Hexahedron'}
ATTRIBUTE = {1: 'Scalar', 3: 'Vector', 6: 'Tensor6', 9: 'Tensor'}
FLOAT64 = {'class': 'float', 'bits': 64, 'order': 'little'}
INT64 = {'class': 'int', 'bits': 64, 'order': 'little'}


def count_of(data, width, explicit, at, what):
    if data['source'] == 'values':
        n = len(data.get('values') or [])
        if not n or n % width:
            fail('INVALID_HDF5_MESH', '%s values hold whole rows of %d numbers' % (what, width), at + '.values', values=n)
        if explicit is not None and explicit != n // width:
            fail('INVALID_HDF5_MESH', 'the explicit count differs from the supplied values', at, count=explicit, rows=n // width)
        return n // width
    if data['source'] in ('input', 'range', 'linspace'):
        if explicit is None:
            fail('INVALID_HDF5_MESH', '%s from inputs or generators declare their row count' % what, at)
        return explicit
    fail('INVALID_HDF5_MESH', '%s take values, input, range or linspace data' % what, at + '.source')


def plan(p):
    if not p.get('file'):
        p['file'] = {'name': 'mesh.h5'}
    f = operations.file_settings(p, 'mesh.h5')
    mesh = p['mesh']
    dim = mesh['dimension']
    n_points = count_of(mesh['points'], dim, mesh.get('pointCount'), '$.mesh.points', 'points')
    times = p['times']
    if any(not math.isfinite(t) for t in times) or any(b <= a for a, b in zip(times, times[1:])):
        fail('INVALID_HDF5_MESH', 'times are finite and strictly increasing', '$.times')
    objects = [{'path': '/time', 'type': FLOAT64, 'shape': [len(times)], 'data': {'source': 'values', 'values': list(times)},
                'units': p['timeUnits'], 'scale': 'time'},
               {'path': '/mesh/points', 'type': FLOAT64, 'shape': [n_points, dim], 'data': mesh['points'], 'units': mesh['units'],
                'attributes': [{'name': 'coordinates', 'value': 'XYZ' if dim == 3 else 'XY'}]}]
    blocks, names = [], set()
    total_cells = 0
    for i, c in enumerate(mesh['cells']):
        at = f'$.mesh.cells[{i}]'
        name = c.get('name', c['type'])
        if not model.NAME.fullmatch(name) or name in names:
            fail('INVALID_HDF5_MESH', 'cell block names are unique HDF5 names', at + '.name')
        names.add(name)
        if dim == 2 and c['type'] in ('tetrahedron', 'pyramid', 'wedge', 'hexahedron'):
            fail('INVALID_HDF5_MESH', 'volume cells need dimension 3', at + '.type')
        k = NODES[c['type']]
        m = count_of(c['connectivity'], k, c.get('count'), at + '.connectivity', 'connectivity')
        blocks.append({'name': name, 'type': c['type'], 'count': m, 'nodes': k, 'at': at})
        objects.append({'path': '/mesh/%s/connectivity' % name, 'type': INT64, 'shape': [m, k], 'data': c['connectivity'],
                        'attributes': [{'name': 'cell_type', 'value': c['type']}]})
        total_cells += m
    fields = []
    seen = set()
    for i, fld in enumerate(p['fields']):
        at = f'$.fields[{i}]'
        if not model.NAME.fullmatch(fld['name']) or fld['name'] in seen:
            fail('INVALID_HDF5_MESH', 'field names are unique HDF5 names', at + '.name')
        seen.add(fld['name'])
        if len(fld['steps']) != len(times):
            fail('INVALID_HDF5_MESH', 'each field gives one data record per time', at + '.steps', steps=len(fld['steps']), times=len(times))
        if fld['association'] == 'cell' and len(blocks) != 1:
            fail('INVALID_HDF5_MESH', 'cell-associated fields need exactly one cell block', at + '.association')
        rows = n_points if fld['association'] == 'point' else total_cells
        comps = fld['components']
        t = fld.get('type', FLOAT64)
        shape = [rows] if comps == 1 else [rows, comps]
        for j, d in enumerate(fld['steps']):
            objects.append({'path': '/fields/%s/step_%d' % (fld['name'], j), 'type': t, 'shape': shape, 'data': d, 'units': fld['units'],
                            'attributes': [{'name': 'time', 'type': FLOAT64, 'value': times[j]},
                                           {'name': 'association', 'value': fld['association']}]})
        fields.append({'name': fld['name'], 'association': fld['association'], 'components': comps, 'shape': shape})
    ctx = model.context(p)
    p['file'] = model.plan_file(f, '$.file', ctx['dependencies'])
    if p['file']['driver'] in ('family', 'split'):
        fail('INVALID_HDF5_MESH', 'XDMF heavy data names one HDF5 file; use the sec2, stdio or core driver', '$.file.driver')
    storage = p.get('storage')
    planned = []
    for i, o in enumerate(objects):
        o = {**o, 'attributes': o.get('attributes', [])}
        o.setdefault('dimensions', [])
        o['kind'] = 'dataset'
        if storage and o['path'].startswith(('/mesh/', '/fields/')):
            o['storage'] = dict(storage)
        planned.append(model.plan_object(validated(o, f'$.objects[{i}]'), f'$.mesh.objects[{i}]', ctx))
    p['objects'] = planned
    p['links'] = []
    p['extracts'] = []
    p['rawFiles'] = []
    p['inputs'] = list(ctx['inputs'].values())
    p['dependencies'] = list(ctx['dependencies'].values())
    p['xdmf'] = p['file']['name'].rsplit('.', 1)[0] + '.xdmf'
    p['blocks'] = [{k: v for k, v in b.items() if k != 'at'} for b in blocks]
    p['meshFields'] = fields
    p['pointCount'] = n_points
    p['dimension'] = dim
    p['mesh'] = {'native': {'xdmf': p['xdmf'], 'xml': xdmf_text(p)}}
    p['losses'] = operations.LOSSES['writeMeshFields']
    return p


def validated(o, at):
    from schemaxis.core.declarations import validate_arguments
    return validate_arguments(model.OBJECT['properties'], o, location=at)


def item(p, path, dims, number='Float', precision=8):
    return ('<DataItem Dimensions="%s" NumberType="%s" Precision="%d" Format="HDF">%s:%s</DataItem>'
            % (' '.join(str(d) for d in dims), number, precision, p['file']['name'], path))


def xdmf_text(p):
    objects = {o['path']: o for o in p['objects']}
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<Xdmf Version="3.0">', ' <Domain>',
             '  <Grid Name="series" GridType="Collection" CollectionType="Temporal">']
    times = objects['/time']['data']['values']
    points = objects['/mesh/points']
    geometry = 'XYZ' if points['shape'][1] == 3 else 'XY'
    for j, t in enumerate(times):
        lines.append('   <Grid Name="step_%d" GridType="%s"%s>' % (j, 'Collection' if len(p['blocks']) > 1 else 'Uniform',
                                                                ' CollectionType="Spatial"' if len(p['blocks']) > 1 else ''))
        lines.append('    <Time Value="%r"/>' % float(t))
        for b in p['blocks']:
            indent = '    ' if len(p['blocks']) == 1 else '     '
            if len(p['blocks']) > 1:
                lines.append('    <Grid Name="%s" GridType="Uniform">' % b['name'])
            lines.append(indent + '<Topology TopologyType="%s" NumberOfElements="%d"%s>' % (
                TOPOLOGY[b['type']], b['count'], ' NodesPerElement="%d"' % b['nodes'] if b['type'] in ('vertex', 'line') else ''))
            lines.append(indent + ' ' + item(p, '/mesh/%s/connectivity' % b['name'], [b['count'], b['nodes']], 'Int', 8))
            lines.append(indent + '</Topology>')
            lines.append(indent + '<Geometry GeometryType="%s">' % geometry)
            lines.append(indent + ' ' + item(p, '/mesh/points', points['shape']))
            lines.append(indent + '</Geometry>')
            for fld in p['meshFields']:
                path = '/fields/%s/step_%d' % (fld['name'], j)
                o = objects[path]
                rt = model.resolved(o['type'])
                number = 'Float' if rt['class'] == 'float' else 'Int' if rt['class'] == 'int' else 'UInt'
                lines.append(indent + '<Attribute Name="%s" AttributeType="%s" Center="%s">' % (
                    fld['name'], ATTRIBUTE[fld['components']], 'Node' if fld['association'] == 'point' else 'Cell'))
                lines.append(indent + ' ' + item(p, path, o['shape'], number, rt['bits'] // 8))
                lines.append(indent + '</Attribute>')
            if len(p['blocks']) > 1:
                lines.append('    </Grid>')
        lines.append('   </Grid>')
    lines += ['  </Grid>', ' </Domain>', '</Xdmf>', '']
    return '\n'.join(lines)


def run(p, directory, paths, deadline, captured):
    from . import adaptor
    values = adaptor.host_values(p, captured)
    for b in p['blocks']:
        conn = values['/mesh/%s/connectivity' % b['name']]
        for r in range(b['count']):
            row = conn[r * b['nodes']:(r + 1) * b['nodes']]
            if any(not 0 <= v < p['pointCount'] for v in row):
                fail('INVALID_HDF5_MESH', 'connectivity indices are zero-based point indices below the point count',
                     '$.mesh.cells.%s.connectivity' % b['name'], cell=r, points=p['pointCount'])
            if len(set(row)) != len(row) and b['type'] != 'vertex':
                fail('INVALID_HDF5_MESH', 'a cell repeats a point index (degenerate cell)', '$.mesh.cells.%s.connectivity' % b['name'], cell=r)
    for v in values['/mesh/points']:
        if isinstance(v, str):
            fail('INVALID_HDF5_MESH', 'point coordinates are finite', '$.mesh.points')
    report = adaptor.run_create(p, directory, paths, deadline, captured)
    report['mesh'] = mesh_report(p, values)
    return report


def mesh_report(p, values):
    return {'points': p['pointCount'], 'blocks': p['blocks'], 'fields': p['meshFields'], 'steps': len(p['times']),
            'measures': measures(p, values)}


def measures(p, values):
    """Independent geometric summary: signed volume/area totals per block (orientation check)."""
    pts = values['/mesh/points']
    dim = p['dimension']
    P = [pts[i * dim:(i + 1) * dim] for i in range(p['pointCount'])]
    out = {}
    for b in p['blocks']:
        conn = values['/mesh/%s/connectivity' % b['name']]
        rows = [conn[r * b['nodes']:(r + 1) * b['nodes']] for r in range(b['count'])]
        if b['type'] == 'tetrahedron' and dim == 3:
            vols = [tet(P[a], P[b_], P[c], P[d]) for a, b_, c, d in rows]
            out[b['name']] = {'volume': sum(vols), 'negativeCells': sum(1 for v in vols if v <= 0)}
        elif b['type'] == 'triangle':
            areas = [tri(P[a], P[b_], P[c]) for a, b_, c in rows]
            out[b['name']] = {'area': sum(areas), 'degenerateCells': sum(1 for x in areas if x <= 0)}
    return out


def tet(a, b, c, d):
    u = [b[i] - a[i] for i in range(3)]
    v = [c[i] - a[i] for i in range(3)]
    w = [d[i] - a[i] for i in range(3)]
    return (u[0] * (v[1] * w[2] - v[2] * w[1]) - u[1] * (v[0] * w[2] - v[2] * w[0]) + u[2] * (v[0] * w[1] - v[1] * w[0])) / 6.0


def tri(a, b, c):
    if len(a) == 2:
        return abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])) / 2.0
    u = [b[i] - a[i] for i in range(3)]
    v = [c[i] - a[i] for i in range(3)]
    x = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
    return math.sqrt(sum(t * t for t in x)) / 2.0


def check_xdmf(p, directory, expected):
    from . import adaptor
    data = adaptor.bounded(directory / p['xdmf'])
    if data.decode('utf-8') != xdmf_text(p):
        fail('VERIFICATION_FAILED', 'XDMF text differs from the planned description', p['xdmf'])
    root = ElementTree.fromstring(data)
    checked = 0
    for element in root.iter('DataItem'):
        file_name, path = element.text.strip().split(':', 1)
        obj = expected['objects'].get(path)
        dims = [int(x) for x in element.get('Dimensions').split()]
        if file_name != p['file']['name'] or obj is None or obj['shape'] != dims or obj['type'].get('bits', 0) // 8 != int(element.get('Precision')):
            fail('VERIFICATION_FAILED', 'an XDMF DataItem does not match its HDF5 dataset', p['xdmf'], item=element.text.strip())
        checked += 1
    steps = [float(t.get('Value')) for t in root.iter('Time')]
    if steps != [float(v) for v in p['times']]:
        fail('VERIFICATION_FAILED', 'XDMF times differ from the planned times', p['xdmf'])
    return {'file': p['xdmf'], 'dataItems': checked, 'steps': len(steps)}
