import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {launch} from '../../src/schemaxis/studio_ui/tests/fixtures/editor/cdp.mjs';
const root=fileURLToPath(new URL('../../src/schemaxis_viewer/web/',import.meta.url));
const repository=fileURLToPath(new URL('../../',import.meta.url));
const choose=async(s,selector,value)=>s.evaluate(`(()=>{const input=document.querySelector(${JSON.stringify(selector)});input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('change'));})()`);
const click=(s,selector)=>s.evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);

test('local folder browser, Open/Add, recursion, paths, types, recent folders, themes and bulk selection',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'artifact-library-'));let server,s;
 try{
  const first=join(dir,'one'),second=join(dir,'two');await mkdir(join(first,'nested'),{recursive:true});await mkdir(join(first,'empty'));await mkdir(second);
  const svg=value=>`<svg xmlns="http://www.w3.org/2000/svg" width="80" height="50"><rect width="80" height="50" fill="${value}"/></svg>`;
  for(let n=0;n<130;n++)await writeFile(join(first,`image_${String(n).padStart(3,'0')}.svg`),svg('#369'));
  await writeFile(join(first,'nested','deep.svg'),svg('#936'));await writeFile(join(first,'readme.txt'),'first folder');await writeFile(join(first,'clip.mp4'),'media placeholder');
  await writeFile(join(second,'new.txt'),'second folder');
  server=spawn('python3',['-u','-m','schemaxis_viewer','--no-browser'],{cwd:repository,env:{...process.env,PYTHONPATH:join(repository,'src'),XDG_STATE_HOME:join(dir,'state')},stdio:['ignore','pipe','pipe']});
  const url=await new Promise((resolve,reject)=>{let output='';const timer=setTimeout(()=>reject(Error('Viewer startup timed out')),10000);server.stdout.on('data',data=>{output+=data;const match=/Artifact viewer: (http:\/\/\S+)/.exec(output);if(match){clearTimeout(timer);resolve(match[1]);}});server.once('error',reject);});
  s=await launch({root,path:'/index.html',width:1500,height:1000});await s.send('Page.navigate',{url});await s.wait('Boolean(window.artifactViewer)','local viewer ready');
  const open=async(path,replace)=>{
   await click(s,replace?'#open-folder':'#add-folder');await s.wait('Boolean(document.querySelector("dialog[open] .primary:not(:disabled)"))','local folder chooser');
   await s.evaluate(`document.querySelector('[aria-label="Local folder path"]').value=${JSON.stringify(path)}`);
   await click(s,'dialog[open] .primary');await s.wait('!document.querySelector("dialog[open]")','folder opened');
  };
  await open(first,true);assert.equal(await s.evaluate('artifactViewer.items.length'),133);
  assert.equal(await s.evaluate('document.querySelector("#title").textContent'),'All outputs');
  await choose(s,'#type-filter','image');assert.equal(await s.evaluate('document.querySelectorAll(".card").length'),121);
  await s.evaluate('document.querySelector("#main").scrollTop=document.querySelector("#main").scrollHeight');
  await s.wait('document.querySelectorAll(".card").length===131','all files become available by scrolling, past the first 120');
  await s.evaluate(`artifactViewer.setTheme('dark',{save:false})`);await click(s,'#theme');assert.equal(await s.evaluate('document.documentElement.dataset.theme'),'light');
  assert.equal(await s.evaluate('getComputedStyle(document.body).backgroundColor'),'rgb(244, 245, 247)');
  await click(s,'#theme');assert.equal(await s.evaluate('document.documentElement.dataset.theme'),'dark');
  await click(s,'#deselect-all');assert.equal(await s.evaluate('document.querySelectorAll(".card-preview").length'),0);
  await click(s,'#select-all');assert.ok(await s.evaluate('document.querySelectorAll(".card-preview").length')>=120);
  const rowSelector='[aria-label="Select row 1 of Numbered images"]';
  const rowIds=await s.evaluate('Array.from(document.querySelector(".gallery-row").querySelectorAll(".card"),card=>card.dataset.fileId)');
  await click(s,rowSelector);
  assert.equal(await s.evaluate(`Array.from(document.querySelectorAll('.card')).filter(card=>${JSON.stringify(rowIds)}.includes(card.dataset.fileId)).every(card=>!card.querySelector('.card-preview'))`),true);
  assert.equal(await s.evaluate(`document.querySelector('[aria-label="Show sequence Numbered images"]').indeterminate`),true);
  await click(s,'[aria-label="Show sequence Numbered images"]');
  assert.equal(await s.evaluate(`document.querySelector('[aria-label="Show sequence Numbered images"]').checked`),true);
  await click(s,'[aria-label="Show sequence Numbered images"]');
  assert.equal(await s.evaluate(`document.querySelectorAll('[data-section-index="0"] .card-preview').length`),0);
  await click(s,'#select-all');await choose(s,'#library-view','folders');await click(s,'#recursive');
  assert.equal(await s.evaluate('document.querySelectorAll(".card").length'),120);
  await click(s,'#foldernav [data-folder]');await click(s,'#foldernav [data-folder="nested"]');
  assert.equal(await s.evaluate('document.querySelectorAll(".card").length'),1);
  assert.match(await s.evaluate('document.querySelector(".file-relative-path").textContent'),/nested\/deep.svg/);
  assert.match(await s.evaluate('document.querySelector(".breadcrumbs").textContent'),/one.*nested/);
  await click(s,'[aria-label="Show all outputs"]');
  await click(s,'#foldernav [data-folder]');await click(s,'#foldernav [data-folder="empty"]');
  assert.equal(await s.evaluate('document.querySelectorAll(".card").length'),0);
  assert.match(await s.evaluate('document.querySelector("#content").textContent'),/No matching files/);
  await click(s,'[aria-label="Show all outputs"]');
  await choose(s,'#type-filter','video');assert.equal(await s.evaluate('document.querySelectorAll(".card").length'),1);
  await click(s,'#toggle-library');assert.equal(await s.evaluate('getComputedStyle(document.querySelector(".library")).display'),'none');await click(s,'#toggle-library');
  await open(second,false);assert.equal(await s.evaluate('artifactViewer.items.length'),134,'Add folder appends');
  await open(second,true);assert.equal(await s.evaluate('artifactViewer.items.length'),1,'Open folder replaces');
  await choose(s,'#library-view','recent');
  await s.evaluate(`[...document.querySelectorAll('.recent-entry')].find(button=>button.querySelector('strong').textContent==='one').click()`);
  await s.wait('artifactViewer.items.length===133','recent collection reopened from local paths');
  assert.equal(s.exceptions.length,0,JSON.stringify(s.exceptions));
  assert.deepEqual(s.logs.filter(line=>/violates.*Content Security|Refused to (execute|load)/i.test(line)),[]);
 }finally{await s?.close();if(server&&server.exitCode===null){server.kill();await new Promise(resolve=>server.once('exit',resolve));}await rm(dir,{recursive:true,force:true});}
});
