def finalize(directory):
    """Refresh every ordinary mutable binding and require publication_metadata.verify to pass: only semantics may then fail."""
    directory = Path(directory)
    p = w.plan(json.loads((directory / 'authored.json').read_text()))
    captured = json.loads((directory / 'captures.json').read_text())
    names = [n for e in captured['items'] if e['fault'] is None for n in [e['file'], *([e['sidecar']['file']] if e['sidecar'] else [])]]
    for stage_name in ('listing', 'repeat'):
        atomic_json(directory / (stage_name + '-inputs.json'), {'files': {n: w.file_digest(directory, n, w.evidence_limit(n)) for n in w.stage_names(stage_name, names)}})
    receipt = json.loads((directory / 'verification.json').read_text())
    receipt['evidence'] = {n: w.file_digest(directory, n, w.evidence_limit(n)) for n in receipt['evidence']}
    receipt['artifacts'] = w.artifacts(directory, p)
    atomic_json(directory / 'verification.json', receipt)
    publication_metadata.finalise(directory)
    assert publication_metadata.verify(directory)['verified'], 'publication metadata must verify after the refresh'


