def native_controls(out, exe, report):
    """Real ExifTool 13.55 over the repair fixtures: a genuine native disagreement, GPS references, near-zero rationals and mixed readable/malformed sources.

    The fixtures are private copies under the output directory (no shared staging). Expected values are hand-written from the fixture table.
    """
    fixtures = out / 'control-fixtures'
    fixtures.mkdir()
    for name in ('north-gate', 'padded-make', 'south-west-sea', 'zero-refs', 'default-altitude', 'near-zero', 'mixed-sources', 'ridge-line', 'repeated-lat-ref', 'repeated-lon-ref', 'repeated-alt-ref'):
        (fixtures / (name + '.jpg')).write_bytes((FIXTURES / (name + '.jpg')).read_bytes())

    def items(*names): return {'items': [{'id': n.replace('-', '_'), 'path': str(fixtures / (n + '.jpg'))} for n in names]}

    def values(directory, item):
        metadata = json.loads((directory / 'metadata.json').read_text())
        found = next(i for i in metadata['items'] if i['id'] == item)
        return found, {f['field']: f for f in found.get('fields', [])}

    def native_observations(directory, item):
        native = json.loads((directory / 'native-observations.json').read_text())
        return [o for f in next(i for i in native['items'] if i['id'] == item)['files'] for o in f['observations']]

    def observed(directory, item, name):
        return [o['value'] for o in native_observations(directory, item) if o['name'] == name]
    # 1. a real disagreement: ExifTool trims the trailing space of Make that the independent reader keeps; one item is refused, the set is a verified partial set
    run(out, 'real-partial', {'version': V, 'operation': 'inspectMetadata', 'media': {'items': [{'id': 'good', 'path': str(fixtures / 'north-gate.jpg')}, {'id': 'padded', 'path': str(fixtures / 'padded-make.jpg')}]},
                              'profiles': ['device'], 'nativeListing': True}, exe)
    d = out / 'real-partial'
    result = json.loads((d / 'result.json').read_text())
    assert (result['status'], result['verified'], result['items'], result['succeeded'], result['faulted'], result['setStatus']) == ('succeeded', True, 2, 1, 1, 'partial'), result
    assert result['nativeReplay'] == 'fresh-replay-matched', result
    assert [r['SourceFile'] for r in json.loads((d / 'listing.stdout').read_text())] == ['captured/good.jpg', 'captured/padded.jpg'], 'the retained listing covers both admitted captures'
    assert sorted(json.loads((d / 'listing-inputs.json').read_text())['files']) == ['captured/good.jpg', 'captured/padded.jpg']
    again = w.verify(d, executable=str(exe))
    assert again['nativeReplay'] == 'fresh-replay-matched' and again['succeeded'] == 1 and again['faulted'] == 1, again
    good, _ = values(d, 'good')
    padded, _ = values(d, 'padded')
    assert (good['status'], padded['status']) == ('ok', 'fault'), (good['status'], padded['status'])
    assert padded['fault']['code'] == 'NATIVE_ANCHOR_MISMATCH' and padded['fault']['location'] == 'captured/padded.jpg', padded['fault']
