def sha(data): return base.sha256(data)


def stage():
    try:
        STAGING.mkdir(mode=0o700)
    except FileExistsError:
        raise SystemExit('refusing pre-existing staging path %s; inspect and remove its stale contents yourself' % STAGING)
    info = STAGING.lstat()
    base.OWNED[STAGING] = (info.st_dev, info.st_ino)
    for name in TOP:
        for suffix in ('.jpg',):
            base.write(STAGING / (name + suffix), (FIXTURES / (name + suffix)).read_bytes())
    for name in ('quay-side.xmp', 'sidecar-only.xmp'):
        base.write(STAGING / name, (FIXTURES / name).read_bytes())
    (STAGING / 'workbench').mkdir()
    info = (STAGING / 'workbench').lstat()
    base.OWNED[STAGING / 'workbench'] = (info.st_dev, info.st_ino)
    for name in FOLDER:
        base.write(STAGING / 'workbench' / name, (FIXTURES / name).read_bytes())
    base.write(STAGING / 'harbour-light-copy.jpg', (FIXTURES / 'harbour-light.jpg').read_bytes())


def unstage():
    for path, identity in sorted(base.OWNED.items(), key=lambda kv: -len(str(kv[0]))):
        try:
            info = path.lstat()
            if (info.st_dev, info.st_ino) != identity:
                continue
            path.rmdir() if path.is_dir() and not path.is_symlink() else path.unlink()
        except (FileNotFoundError, OSError):
            pass


def cells(directory, name): return list(csv.reader(io.StringIO((directory / name).read_text(encoding='utf-8'))))


