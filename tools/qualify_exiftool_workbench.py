SUMMARY_HEADER = ['Column', 'COUNT', 'SUM', 'AVERAGE', 'MIN', 'MAX', 'STDEV', 'MISSING']  # literal A1:H1 of Summary, not derived from the producer's metric list


def check_workbook(path, rows, summary, odf):
    """Every native Data and Summary cell against literal rows; returns the cell count (see ``check_workbook_detail`` for the parts)."""
    return check_workbook_detail(path, rows, summary, odf)['cells']


def check_workbook_detail(path, rows, summary, odf, header=SUMMARY_HEADER):
    """Every native Data and Summary cell against literal rows (the shared oracle's column map is narrower than this table).

    The count is the Data cells that hold a value plus every Summary cell (header row included). The eight Summary header cells are checked
    by TEXT against ``header`` (the literal row above; a probe may pass a different one to show that nothing else differs), the rest by value or formula.
    """
    sheets, names = (calc_oracle.ods_oracle if odf else calc_oracle.xlsx_oracle)(path)
    assert list(sheets) == ['Data', 'Summary'], list(sheets)
    cells_, formulas, _ = sheets['Data']
    expected = calc_oracle.literal_cells(rows)
    assert set(cells_) == set(expected), (path.name, sorted(set(cells_) ^ set(expected)))
    assert not formulas, 'formula in Data'
    for ref, value in expected.items():
        got = cells_[ref]
        if isinstance(value, str):
            assert type(got) is str and got == value, (path.name, ref, got, value)
        else:
            assert type(got) is float and (got == value if value == 0 else math.isclose(got, value, rel_tol=1e-14, abs_tol=0)), (path.name, ref, got, value)
    count, cache, marks = len(rows) - 1, sheets['Summary'][0], sheets['Summary'][1]
    for index, line in enumerate(summary):
        row = index + 2
        assert cache.get('A%d' % row) == line[0], (path.name, 'summary label', row)
        for offset, metric in enumerate(calc_oracle.METRICS):
            ref = 'BCDEFGH'[offset] + str(row)
            wanted = line[1 + offset]
            if metric in ('COUNT', 'COUNTBLANK'):
                assert cache[ref] == wanted, (path.name, ref, cache[ref], wanted)
            else:
                assert math.isclose(cache[ref], wanted, rel_tol=1e-9, abs_tol=1e-12), (path.name, ref, cache[ref], wanted)
            column = line[8]
            text = marks[ref]
            assert text == ('of:=%s([$Data.%s2:.%s%d])' % (metric, column, column, count + 1) if odf else '%s(Data!%s2:%s%d)' % (metric, column, column, count + 1)), (path.name, ref, text)
    assert len(marks) == 7 * len(summary) and set(cache) == {'%s%d' % (c, r) for r in range(1, len(summary) + 2) for c in 'ABCDEFGH'}, 'summary cells'
    found = [cache['%s1' % c] for c in 'ABCDEFGH']
    assert found == header and all(type(v) is str for v in found), (path.name, 'summary header text', found)
    return {'dataCells': len(cells_), 'summaryCells': len(cache), 'summaryHeaderTextChecks': len(found), 'cells': len(cells_) + len(cache)}


def check_both_formats(directory, rows, summary):
    """Both native workbooks (XLSX then ODS) against the same literal rows; the exact per-format counts and header checks."""
    detail = {extension: check_workbook_detail(directory / ('analysis.' + extension), rows, summary, odf=odf) for extension, odf in (('xlsx', False), ('ods', True))}
    return {'cells': sum(d['cells'] for d in detail.values()), 'perFormat': detail}


def header_probes(directory, rows, summary, out):
    """ARTIFACT-HEADER PROBES (controls of this qualifier's own oracle: neither production semantic mutants nor native events).

    Each probe copies one native-produced workbook, changes the text of ONE Summary header cell in the file bytes and nothing else, then shows that
    the literal-header oracle refuses it while the same oracle, told the changed header, accepts it (so that header text is the only difference).
    """
    from zipfile import ZIP_STORED, ZipFile
    out.mkdir(parents=True, exist_ok=True)
    probes = []
    for extension, odf, header_index, find, replace in (('xlsx', False, 7, 'MISSING', 'MISSING_'), ('ods', True, 0, 'Column', 'column')):
        source = directory / ('analysis.' + extension)
        target = out / ('header-probe-analysis.' + extension)
        with ZipFile(source) as archive, ZipFile(target, 'w') as written:
            for info in archive.infolist():
                data = archive.read(info.filename)
                if info.filename == ('xl/sharedStrings.xml' if not odf else 'content.xml'):
                    text = data.decode('utf-8')
                    if odf:
                        head, marker, tail = text.partition('table:name="Summary"')
                        assert marker and tail.count('>%s</text:p>' % find) == 1, 'the Summary table holds exactly one %s string cell' % find
                        text = head + marker + tail.replace('>%s</text:p>' % find, '>%s</text:p>' % replace, 1)
                    else:
                        assert text.count('>%s</t>' % find) == 1, 'the shared string %s is used by exactly one cell' % find
                        text = text.replace('>%s</t>' % find, '>%s</t>' % replace, 1)
                    data = text.encode('utf-8')
                written.writestr(info, data, compress_type=ZIP_STORED if info.filename == 'mimetype' else info.compress_type)
        refused = None
        try:
            check_workbook_detail(target, rows, summary, odf)
        except AssertionError as error:
            refused = str(error)
        assert refused is not None and 'summary header text' in refused, (extension, refused)
        changed = list(SUMMARY_HEADER)
        changed[header_index] = replace
        accepted = check_workbook_detail(target, rows, summary, odf, header=changed)  # every other Data and Summary check still passes
        probes.append({'probe': 'summary-header-' + extension, 'kind': 'artifact-header probe of the qualifier oracle (not a production semantic mutant, not a native event)',
                       'changedCell': 'ABCDEFGH'[header_index] + '1', 'from': find, 'to': replace, 'literalHeaderOracleRefused': True, 'otherCellsStillPass': accepted['cells']})
    return probes


def workflow_handoff(out, exe, soffice, report):
    """Exposure profile CSV -> Calc readTypedCSV through the real scheduler; every Data and Summary cell of both formats read back independently."""
    graph = example('exiftool-exposure-calc-workflow.json')
    locations = {'exiftool': str(exe), 'calc': str(soffice)}
    target = out / 'handoff-exposure'
    workflow.execute(graph, target, locations=locations, timeout=300)
    assert workflow.verify(target)['verified']
    producer = next((target / 'exposure').glob('*/attempt-*/profile-exposure.csv'))
    consumer = next((target / 'workbook').glob('*/attempt-*/analysis.xlsx')).parent
    assert (consumer / 'source.csv').read_bytes() == producer.read_bytes(), 'consumer captured bytes differ from the real ExifTool artifact'
    summary = []
    for label, column in NUMBER_COLUMNS.items():
        values = [r[EXPOSURE_COLUMNS.index(label)] for r in EXPOSURE_ROWS[1:] if r[EXPOSURE_COLUMNS.index(label)] is not None]
        summary.append([label, len(values), math.fsum(values), statistics.fmean(values), min(values), max(values), statistics.stdev(values), len(EXPOSURE_ROWS) - 1 - len(values), column])
    checked = check_both_formats(consumer, EXPOSURE_ROWS, summary)
    cells_ = checked['cells']
    probes = header_probes(consumer, EXPOSURE_ROWS, summary, out / 'header-probes')
    resumed = workflow.execute(graph, target, locations=locations, timeout=300, resume=True)
    assert all(job.get('reused') for job in resumed['jobs']), resumed['jobs']
    # same-path photo bytes change: producer and consumer must re-run
    base.write(STAGING / 'harbour-light.jpg', author.workbench_jpeg('orchard-gate', 7))
    changed = workflow.execute(graph, target, locations=locations, timeout=300, resume=True)
    assert not any(job.get('reused') for job in changed['jobs']), 'stale reuse after photo bytes changed'
    assert workflow.verify(target)['verified']
    base.write(STAGING / 'harbour-light.jpg', (FIXTURES / 'harbour-light.jpg').read_bytes())
    faults = []
    for label, mutate, code, fragment in (
            ('required-column-has-null', lambda g: g['operations'][1]['document']['nodes'][0]['options']['columns'][9].pop('nullable'), 'INVALID_TABLE', 'null token'),
            ('header-differs', lambda g: g['operations'][1]['document']['nodes'][0]['options']['columns'][1].update(name='time'), 'INVALID_TABLE', 'header'),
            ('number-kind-for-state-text', lambda g: g['operations'][1]['document']['nodes'][0]['options']['columns'][2].update(kind='number'), 'INVALID_TABLE', 'number'),
            ('metadata-json-as-table', lambda g: g['operations'][1]['document']['nodes'][0]['options']['file'].update(index=0), 'TYPE_MISMATCH', None)):
        case = copy.deepcopy(graph)
        mutate(case)
        fault = base.refused(lambda: workflow.execute(case, out / ('handoff-bad-' + label), locations=locations, timeout=300), code, fragment=fragment)
        assert not list((out / ('handoff-bad-' + label)).rglob('analysis.xlsx')), 'workbook published for ' + label
        faults.append({'case': label, **fault})
    one = copy.deepcopy(graph)
    one['operations'][0]['document']['media']['items'] = one['operations'][0]['document']['media']['items'][:1]
    faults.append({'case': 'one-photo-number-columns-need-two-values', **base.refused(lambda: workflow.execute(one, out / 'handoff-bad-single', locations=locations, timeout=300), 'INVALID_TABLE', fragment='two present values')})
    report['handoff'] = {'status': 'verified', 'cellsCheckedIndependently': cells_, 'cellsPerFormat': checked['perFormat'], 'headerProbes': probes, 'formats': ['xlsx', 'ods'], 'capturedBytesExactlyProducerArtifact': True, 'reusedOnResume': True, 'samePathPhotoChangeRerunProducerAndConsumer': True,
                         'faults': faults, 'scope': 'Three synthetic photos (exposure profile with absent and present values and State columns) as editable ODS/XLSX; ExifTool metadata is observed text, not certified.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exiftool', type=Path, required=True)
    parser.add_argument('--calc', type=Path)
    parser.add_argument('--output-directory', type=Path, required=True)
    args = parser.parse_args()
    out = args.output_directory.resolve()
    if out.exists():
        raise SystemExit('select a fresh output directory')
    out.mkdir(parents=True)
    exe = args.exiftool.resolve()
    report = {'scope': __doc__.split('\n\n')[0], 'cases': {}, 'controls': {}, 'verified': False, 'startedAt': time.time()}
    stage()
    try:
        report['runtime'] = {'script': exe.name, 'scriptSha256': sha(exe.read_bytes()), 'perl': a.PERL}
        check_inspect(out, exe, report)
        check_variant(out, exe, report)
        check_audit_compare(out, exe, report)
        check_sets(out, exe, report)
        check_item_faults(out, exe, report)
        native_controls(out, exe, report)
        hostile(out, exe, report)
        live_lifecycle(out, exe, report)
        if args.calc:
            workflow_handoff(out, exe, args.calc.resolve(), report)
        else:
            report['handoff'] = {'status': 'unavailable', 'reason': 'no --calc executable supplied; not run, not qualified'}
        report['companions'] = ['tools/qualify_exiftool_agent_loop.py (public agent loop, run-level folder change)', 'tools/qualify_exiftool_folder_reuse.py (folder-set reuse and invalidation)']
        report['verified'] = True
    finally:
        report['finishedAt'] = time.time()
        atomic_json(out / 'acceptance.json', report)
        unstage()
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
