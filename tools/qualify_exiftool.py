def refused(action, code, location=None, fragment=None, **observed):
    try: action()
    except SchemaxisError as error:
        fault = error.fault
        assert fault.code == code, fault.to_dict()
        if location is not None: assert fault.location == location, fault.to_dict()
        if fragment is not None: assert fragment in fault.message, fault.to_dict()
        for key, value in observed.items(): assert fault.observed.get(key) == value, fault.to_dict()
        return fault.to_dict()
    raise AssertionError('invalid photo input/evidence accepted: ' + code)


def document(names, **kw):
    return {'version': 'schemaxis.exiftool/1', 'operation': 'inventoryPhotos', 'photos': [{'id': IDS.get(n, n.replace('-', '_')), 'path': str(STAGING / (n + '.jpg'))} for n in names], **kw}


def strict_pairs(text):
    def pairs(items):
        assert len({k for k, _ in items}) == len(items), 'duplicate JSON key in native output'
        return dict(items)
    return json.loads(text, object_pairs_hook=pairs)


def check_baseline(directory, names, report, label):
    """Compare retained evidence with literal expectations, using only qualifier-owned parsing."""
    directory = Path(directory)
    native = strict_pairs((directory / 'extract.stdout').read_text(encoding='utf-8'))
    assert len(native) == len(names)
    for row, name in zip(native, names):
        assert row['SourceFile'] == f'captured/{IDS[name]}.jpg'
        expected = {**EXPECTED_NATIVE[name], **FRAME}
        got = {k: v for k, v in row.items() if k != 'SourceFile'}
        assert got == expected, (name, got, expected)
        assert all(type(got[k]) is type(v) for k, v in expected.items()), (name, 'JSON type')
    assert (directory / 'extract.stdout').read_bytes() == (directory / 'repeat.stdout').read_bytes() and (directory / 'extract.stderr').read_bytes() == b''
    lines = EXPECTED_CSV.splitlines(True)
    wanted = ''.join([lines[0]] + [lines[1 + ORDER.index(n)] for n in names])
    assert (directory / 'inventory.csv').read_text(encoding='utf-8') == wanted, (label, (directory / 'inventory.csv').read_text())
    parsed = list(csv.reader(io.StringIO((directory / 'inventory.csv').read_text(encoding='utf-8'))))
    assert parsed[0] == [c['name'] for c in COLUMNS] and len(parsed) == len(names) + 1
    metadata = json.loads((directory / 'metadata.json').read_text())
    assert [p['id'] for p in metadata['photos']] == [IDS[n] for n in names] and [p['order'] for p in metadata['photos']] == list(range(1, len(names) + 1))
    for photo, name in zip(metadata['photos'], names):
        data = (FIXTURES / (name + '.jpg')).read_bytes()
        assert photo['sha256'] == sha256(data) and photo['bytes'] == len(data), name
        assert photo['nativeObservations'] == {k: str(v) for k, v in sorted({**EXPECTED_NATIVE[name], **FRAME}.items())}, name
    blob = json.dumps(metadata) + (directory / 'inventory.csv').read_text()
    assert str(STAGING) not in blob and '/tmp/' not in blob and 'GPS' not in json.dumps(metadata['photos']), 'private path or GPS leaked into publications'
    report['cases'][label] = {'photos': list(names), 'inventorySha256': sha256((directory / 'inventory.csv').read_bytes()), 'nativeJsonTypesChecked': True, 'secondFreshProcessIdentical': True}


def finalize(directory):
    """Refresh every ordinary mutable binding (stage inputs, receipt evidence and artifact digests, publication metadata) and require
    publication_metadata.verify to pass, so only semantics can fail verification."""
    directory = Path(directory);p = a.plan(json.loads((directory / 'authored.json').read_text()))
    for stage_name in ('extract', 'repeat'):
        atomic_json(directory / (stage_name + '-inputs.json'), {'files': {n: a.digest(directory, n, a.evidence_limit(n)) for n in a.stage_inputs(stage_name, p)}})
    receipt = json.loads((directory / 'verification.json').read_text())
    receipt['evidence'] = {n: a.digest(directory, n, a.evidence_limit(n)) for n in receipt['evidence']}
    receipt['artifacts'] = a.artifacts(directory)
    atomic_json(directory / 'verification.json', receipt)
    publication_metadata.finalise(directory)
    # the refreshed publication metadata must itself verify before any semantic check runs
    assert publication_metadata.verify(directory)['verified'], 'publication metadata must verify after the refresh'


